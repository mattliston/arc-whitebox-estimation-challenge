

# BEGIN FABLE-ENGINEER2 star-scale TEST (E2-SSC, 2026-09-24; TEST ONLY): on S21s1 + --s1zero, the star term's off-diagonal part
# sub = s2/3 is scaled by _STAR_SCALE = 0.8 (the star diagonal, filled separately, is not scaled). Lead's probe: is the whole star
# over-represented, or was s1 the specific culprit?
_STAR_SCALE = 0.8


def _flms_cov_star(w, C, A):
    if w.ndim != 2 or C.shape != (w.shape[0], w.shape[0]) or A.shape != (w.shape[0], w.shape[0]):
        raise ValueError('FLMS covariance/star shapes')
    if str(w.dtype) != 'float32':
        raise TypeError('FLMS weights must be FP32')
    wt = w.T
    C32 = C.astype(fnp.float32)
    A32 = A if str(A.dtype) == 'float32' else A.astype(fnp.float32)
    Q, B = _lr_factor(A32)
    P1 = wt @ Q
    pushed = P1 @ B
    pw = pushed * wt
    wt2 = wt * wt
    first = _mm(C32, w)
    s2 = (wt2 @ B.T) @ P1.T
    cov = _sym_upper(wt, first)
    Cpre = cov.astype(fnp.float64)
    sub = (s2 / 3) * _STAR_SCALE
    diagonal = fnp.sum(pw * wt, axis=1, dtype=fnp.float64)
    result = sub.astype(fnp.float64)
    fnp.fill_diagonal(result, diagonal)
    return Cpre, result
# END FABLE-ENGINEER2 star-scale TEST
