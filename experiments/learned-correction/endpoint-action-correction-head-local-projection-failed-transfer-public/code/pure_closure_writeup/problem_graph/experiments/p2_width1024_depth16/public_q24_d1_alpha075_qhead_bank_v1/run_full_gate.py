def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb", buffering=0) as handle:
        for block in iter(lambda: handle.read(8 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def array_sha256(value: np.ndarray) -> str:
    array = np.ascontiguousarray(value)
    digest = hashlib.sha256()
    digest.update(array.dtype.str.encode("ascii"))
    digest.update(json.dumps(list(array.shape), separators=(",", ":")).encode("ascii"))
    digest.update(memoryview(array).cast("B"))
    return digest.hexdigest()


def resident_bytes() -> int:
    value = int(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss)
    if sys.platform != "darwin":
        value *= 1024
    return value


def write_json_once(path: Path, payload: dict[str, object]) -> None:
    if path.exists():
        raise FileExistsError(path)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    temporary.replace(path)


def write_array_once(path: Path, value: np.ndarray) -> None:
    with path.open("xb") as handle:
        np.save(handle, value, allow_pickle=False)


def verify_static() -> None:
    expected = {
        SOURCE: SOURCE_SHA256,
        BUILDER: BUILDER_SHA256,
        GENERATOR: GENERATOR_SHA256,
        PREREGISTRATION: PREREGISTRATION_SHA256,
        PARITY: PARITY_SHA256,
    }
    for path, wanted in expected.items():
        observed = sha256(path)
        if observed != wanted:
            raise AssertionError((str(path), observed, wanted))
    prereg = json.loads(PREREGISTRATION.read_text(encoding="utf-8"))
    if prereg.get("status") != "FROZEN_UNLAUNCHED":
        raise AssertionError("preregistration status changed")
    if tuple(prereg.get("call_order", ())) != CALL_ORDER:
        raise AssertionError("preregistered call order changed")
    if tuple(prereg["candidate_gate"]["exact_expected_flops"]) != EXPECTED_CANDIDATE_FLOPS:
        raise AssertionError("preregistered bills changed")
    parity = json.loads(PARITY.read_text(encoding="utf-8"))
    if parity.get("status") != "PASS_TARGET_FREE_TRANSPORT_PARITY":
        raise AssertionError("transport parity admission changed")


def load_module():
    spec = importlib.util.spec_from_file_location("d1_alpha075_qhead_full_gate", SOURCE)
    if spec is None or spec.loader is None:
        raise ImportError(SOURCE)
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def load_fixture(role_rank: int) -> MLP:
    path, expected = FIXTURES[role_rank]
    if sha256(path) != expected:
        raise AssertionError(f"fixture weights changed: {role_rank}")
    weights = np.load(path, mmap_mode="r", allow_pickle=False)
    if weights.dtype != np.dtype("<f4") or weights.shape != (16, 1024, 1024):
        raise AssertionError(f"fixture schema changed: {role_rank}")
    mlp = MLP(
        width=1024,
        depth=16,
        weights=[weights[layer] for layer in range(16)],
        seed=0,
        name="sealed-target-free-weight-fixture",
    )
    mlp.validate()
    return mlp


def load_expected() -> tuple[str, list[np.ndarray]]:
    manifest_path = EXPECTED_DIR / "MANIFEST.json"
    if sha256(manifest_path) != EXPECTED_MANIFEST_SHA256:
        raise AssertionError("expected-output manifest changed")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("status") != "PASS_TARGET_FREE_EXPECTED_OUTPUT_GENERATION":
        raise AssertionError("expected-output authority status changed")
    if tuple(manifest.get("call_order", ())) != CALL_ORDER:
        raise AssertionError("expected-output call order changed")
    bindings = manifest.get("bindings", {})
    required = {
        "candidate_source_sha256": SOURCE_SHA256,
        "preregistration_sha256": PREREGISTRATION_SHA256,
        "transport_parity_result_sha256": PARITY_SHA256,
        "generator_sha256": GENERATOR_SHA256,
        "fixture_weight_sha256": {str(rank): expected for rank, (_, expected) in FIXTURES.items()},
    }
    if bindings != required:
        raise AssertionError({"expected authority bindings": required, "observed": bindings})
    arrays: list[np.ndarray] = []
    files = manifest.get("files", [])
    if len(files) != 3:
        raise AssertionError("expected-output file count changed")
    for ordinal, record in enumerate(files):
        if int(record["ordinal"]) != ordinal or int(record["role_rank"]) != CALL_ORDER[ordinal]:
            raise AssertionError("expected-output roster changed")
        path = EXPECTED_DIR / str(record["name"])
        if sha256(path) != record["file_sha256"]:
            raise AssertionError("expected-output file hash changed")
        value = np.load(path, allow_pickle=False)
        if value.dtype != np.float32 or value.shape != (16, 1024):
            raise AssertionError("expected-output schema changed")
        if not np.isfinite(value).all() or array_sha256(value) != record["array_sha256"]:
            raise AssertionError("expected-output contents changed")
        arrays.append(np.ascontiguousarray(value))
    if array_sha256(arrays[0]) != array_sha256(arrays[2]):
        raise AssertionError("expected rank35 repeat changed")
    return sha256(manifest_path), arrays


def load_incumbent_references() -> list[np.ndarray]:
    arrays = []
    for path, expected in INCUMBENT_REFERENCES:
        if sha256(path) != expected:
            raise AssertionError(f"incumbent reference changed: {path}")
        value = np.load(path, allow_pickle=False)
        if value.dtype != np.float32 or value.shape != (16, 1024) or not np.isfinite(value).all():
            raise AssertionError("incumbent reference schema changed")
        arrays.append(np.ascontiguousarray(value))
    return arrays


def drift(candidate: np.ndarray, reference: np.ndarray) -> dict[str, object]:
    delta = candidate.astype(np.float64) - reference.astype(np.float64)
    layer_rms = np.sqrt(np.mean(delta * delta, axis=1))
    layer_max = np.max(np.abs(delta), axis=1)
    return {
        "per_layer_rms": [float(value) for value in layer_rms],
        "per_layer_maximum_absolute": [float(value) for value in layer_max],
        "global_rms": float(np.sqrt(np.mean(delta * delta))),
        "global_maximum_absolute": float(np.max(np.abs(delta))),
        "final_layer_rms": float(layer_rms[-1]),
        "final_layer_maximum_absolute": float(layer_max[-1]),
    }


def main() -> None:
    verify_static()
    if RESULT.exists() or OUTPUT_DIR.exists():
        raise FileExistsError("full gate already attempted")
    if not EXPECTED_DIR.exists():
        raise FileNotFoundError("run frozen expected-output generator first")
    expected_manifest_sha, expected = load_expected()
    incumbent = load_incumbent_references()
    fixtures = {rank: load_fixture(rank) for rank in sorted(set(CALL_ORDER))}
    module = load_module()
    estimator = module.Estimator()
    OUTPUT_DIR.mkdir(exist_ok=False)
    trials: list[dict[str, object]] = []
    first_hash: str | None = None
    with threadpool_limits(limits=2):
        for ordinal, role_rank in enumerate(CALL_ORDER):
            context = flops.BudgetContext(
                flop_budget=PHASE2_BUDGET,
                wall_time_limit_s=MAX_WALL_SECONDS,
                quiet=True,
                namespace=f"d1_alpha075_qhead_integrated_{ordinal}",
            )
            started = time.perf_counter()
            with context:
                value = estimator.predict(fixtures[role_rank], PHASE2_BUDGET)
            outer_wall = time.perf_counter() - started
            summary = context.summary_dict(by_namespace=False)
            raw = np.asarray(value)
            output = np.ascontiguousarray(raw)
            output_hash = array_sha256(output)
            operation_sum = sum(int(item["flop_cost"]) for item in summary["operations"].values())
            candidate_flops = int(summary["flops_used"])
            authority_drift = drift(output, expected[ordinal])
            incumbent_drift = drift(output, incumbent[ordinal])
            rss = resident_bytes()
            repeat_ok = ordinal != 2 or output_hash == first_hash
            gates = {
                "output_float32_16x1024": bool(raw.dtype == np.float32 and raw.shape == (16, 1024)),
                "output_finite": bool(np.isfinite(output).all()),
                "literal_flops_exact": candidate_flops == EXPECTED_CANDIDATE_FLOPS[ordinal],
                "literal_operation_sum_exact": operation_sum == candidate_flops,
                "incremental_flops_exact": candidate_flops - EXPECTED_INCUMBENT_FLOPS[ordinal] == EXPECTED_INCREMENT[ordinal],
                "flops_below_budget": candidate_flops < PHASE2_BUDGET,
                "outer_wall_below_120s": outer_wall < MAX_WALL_SECONDS,
                "meter_wall_below_120s": float(summary["wall_time_s"]) < MAX_WALL_SECONDS,
                "residual_strictly_below_0_4s": float(summary["residual_wall_time_s"]) < MAX_RESIDUAL_SECONDS,
                "rss_strictly_below_8_gib": rss < MAX_RSS_BYTES,
                "offline_authority_max_abs": authority_drift["global_maximum_absolute"] <= MAX_AUTHORITY_ABS_DELTA,
                "offline_authority_rms": authority_drift["global_rms"] <= MAX_AUTHORITY_RMS_DELTA,
                "repeat_rank35_byte_identical": repeat_ok,
            }
            gates["conjunctive_call_pass"] = all(gates.values())
            output_path = OUTPUT_DIR / f"candidate_{ordinal}_rank{role_rank}.npy"
            write_array_once(output_path, output)
            trial = {
                "ordinal": ordinal,
                "role_rank": role_rank,
                "literal_meter": summary,
                "literal_operation_sum": operation_sum,
                "candidate_flops": candidate_flops,
                "incumbent_flops": EXPECTED_INCUMBENT_FLOPS[ordinal],
                "incremental_flops": candidate_flops - EXPECTED_INCUMBENT_FLOPS[ordinal],
                "outer_wall_seconds": outer_wall,
                "maximum_process_rss_bytes": rss,
                "output_array_sha256": output_hash,
                "output_file_sha256": sha256(output_path),
                "drift_vs_offline_authority": authority_drift,
                "drift_vs_established_incumbent_diagnostic_only": incumbent_drift,
                "gates": gates,
            }
            trials.append(trial)
            print(json.dumps(trial, sort_keys=True), flush=True)
            if ordinal == 0:
                first_hash = output_hash
            if not gates["conjunctive_call_pass"]:
                break

    aggregate = {
        "all_three_calls_completed": len(trials) == 3,
        "all_call_gates_pass": len(trials) == 3 and all(trial["gates"]["conjunctive_call_pass"] for trial in trials),
        "repeat_rank35_byte_identical": len(trials) == 3 and trials[0]["output_array_sha256"] == trials[2]["output_array_sha256"],
        "maximum_residual_wall_seconds": max(float(trial["literal_meter"]["residual_wall_time_s"]) for trial in trials),
        "maximum_process_rss_bytes": max(int(trial["maximum_process_rss_bytes"]) for trial in trials),
        "projected_raw_mse": PROJECTED_RAW,
        "projected_adjusted_score": PROJECTED_ADJUSTED,
        "incumbent_submission_id": 328586,
        "incumbent_raw_mse": INCUMBENT_RAW,
        "incumbent_adjusted_score": INCUMBENT_ADJUSTED,
        "protected_raw_ratio": PROTECTED_RAW_RATIO,
        "conservative_max_fixture_compute_ratio": MAX_COMPUTE_RATIO,
        "projected_adjusted_improves_incumbent": PROJECTED_ADJUSTED < INCUMBENT_ADJUSTED,
    }
    aggregate["conjunctive_pass"] = bool(
        aggregate["all_three_calls_completed"]
        and aggregate["all_call_gates_pass"]
        and aggregate["repeat_rank35_byte_identical"]
        and aggregate["projected_adjusted_improves_incumbent"]
    )
    result = {
        "schema": "q24-d1-alpha075-qhead-full-target-free-gate-v1",
        "status": "PASS_FULL_TARGET_FREE_GATE" if aggregate["conjunctive_pass"] else "FAIL_FULL_TARGET_FREE_GATE",
        "call_order": list(CALL_ORDER),
        "trials": trials,
        "aggregate": aggregate,
        "bindings": {
            "candidate_source_sha256": sha256(SOURCE),
            "builder_sha256": sha256(BUILDER),
            "generator_sha256": sha256(GENERATOR),
            "preregistration_sha256": sha256(PREREGISTRATION),
            "transport_parity_result_sha256": sha256(PARITY),
            "expected_outputs_manifest_sha256": expected_manifest_sha,
            "runner_sha256": sha256(Path(__file__)),
            "fixture_weight_sha256": {str(rank): sha256(path) for rank, (path, _) in FIXTURES.items()},
        },
        "access_declarations": {
            "weights_only": True,
            "target_columns_opened": [],
            "scores_opened": [],
            "names_opened": [],
            "board_opened": False,
            "submission": False,
            "training": False,
            "network": False,
        },
    }
    write_json_once(RESULT, result)
    print(json.dumps({"status": result["status"], "aggregate": aggregate}, sort_keys=True), flush=True)
    if not aggregate["conjunctive_pass"]:
        raise RuntimeError(result["status"])


if __name__ == "__main__":
    main()
